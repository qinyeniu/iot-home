// CQ-3e: host-testable runtime adapter for gateway RF state.
#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "rf_background_execution_plan.h"
#include "rf_command_queue.h"

typedef struct {
    uint32_t now_ms;
    uint32_t last_eval_ms;
    uint16_t node_addr;
    uint32_t last_rx_ms;
    uint32_t confirmed_ms;
    int8_t current_power_dbm;
    uint8_t node_mode;
    uint8_t desired_mode;
    int8_t desired_manual_power_dbm;
    bool policy_apply_pending;
    uint32_t tx_backoff_until_ms;
    bool user_intent_active;
    bool report_waiting;
    bool report_submitting;
    uint32_t wait_started_ms;
    bool dispatch_active;
    bool background_command_active;
    uint32_t active_command_id;
    uint32_t active_command_generation;
    // One-time, non-reused id generated by the integration layer for this
    // evaluation. The adapter consumes the value but does not advance it.
    uint32_t next_command_id;
    uint32_t policy_generation;
} rf_background_runtime_state_t;

typedef enum {
    RF_BG_RUNTIME_ROLLBACK_DONE = 0,
    RF_BG_RUNTIME_ROLLBACK_NOT_MATCHED,
    RF_BG_RUNTIME_ROLLBACK_INVALID_ARG,
} rf_background_runtime_rollback_result_t;

typedef struct {
    rf_background_execution_result_t result;
    rf_background_admission_result_t reject_reason;
    rf_background_runtime_state_t next_state;
    rf_dispatch_cmd_t command;
    bool state_changed;
    bool has_command;
} rf_background_runtime_adapter_result_t;

/*
 * Maps a snapshot of the gateway's main RF runtime variables onto the pure
 * background execution plan, then produces the next runtime state and a
 * command that can be submitted to the single RF queue after releasing the RF
 * lock. The function does not call FreeRTOS, ZBOSS, NVS or network APIs.
 *
 * A rejected evaluation returns an unchanged next state. A stale node keeps
 * the node address and durable desired policy while resetting node power/mode,
 * confirmed time, waiting and background ownership. A READY result records the
 * active command id/generation in next_state.
 */
bool rf_background_runtime_adapter_apply(
    const rf_background_runtime_state_t *state,
    rf_background_runtime_adapter_result_t *result);

/*
 * Rolls back background ownership after rf_cq_submit() has failed. It only
 * clears background state when the same command id and policy generation are
 * still active; it never clears policy_apply_pending and cannot clear a user
 * intent. The caller must snapshot state while holding the RF lock.
 */
bool rf_background_runtime_rollback_command(
    const rf_background_runtime_state_t *state,
    const rf_dispatch_cmd_t *command,
    rf_background_runtime_rollback_result_t *result,
    rf_background_runtime_state_t *next_state);
